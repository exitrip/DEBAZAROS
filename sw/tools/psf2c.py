#!/usr/bin/env python3
"""psf2c.py - convert PSF1/PSF2 console fonts to a C table (ASCII 32..126).

    python3 tools/psf2c.py NAME font.psf.gz [NAME2 font2.psf.gz ...] > lib/dz_font_data.h

Glyphs are found through the font's Unicode table (glyph order is not ASCII
in most console fonts). Output: one byte array per font, rows of
ceil(width/8) bytes, MSB = leftmost pixel.
"""
import gzip, struct, sys

def load(path):
    b = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    if b[:2] == b"\x36\x04":                      # PSF1
        mode, h = b[2], b[3]
        n = 512 if mode & 1 else 256
        w, size, off = 8, h, 4
        glyphs = [b[off + i * size: off + (i + 1) * size] for i in range(n)]
        uni = {}
        if mode & 2:                              # unicode table: u16, 0xFFFF ends a glyph
            p, g = off + n * size, 0
            while g < n and p + 1 < len(b):
                (u,) = struct.unpack_from("<H", b, p); p += 2
                if u == 0xFFFF: g += 1
                elif u != 0xFFFE: uni.setdefault(u, g)
        return w, h, glyphs, uni
    if b[:4] == b"\x72\xb5\x4a\x86":              # PSF2
        _, _, hsz, flags, n, size, h, w = struct.unpack_from("<8I", b, 0)
        glyphs = [b[hsz + i * size: hsz + (i + 1) * size] for i in range(n)]
        uni = {}
        if flags & 1:                             # UTF-8 table: 0xFF ends a glyph
            p, g, cur = hsz + n * size, 0, b""
            while g < n and p < len(b):
                c = b[p]; p += 1
                if c == 0xFF:
                    for ch in cur.split(b"\xfe")[0].decode("utf-8", "ignore"):
                        uni.setdefault(ord(ch), g)
                    cur, g = b"", g + 1
                else:
                    cur += bytes([c])
        return w, h, glyphs, uni
    raise SystemExit("not a PSF font: " + path)

out = ["/* GENERATED by sw/tools/psf2c.py - do not edit.",
       " * dz pixel fonts: bitmaps derived from \"Terminus Font\" by Dimitar Toshkov",
       " * Zhekov (c) 2010, SIL Open Font License 1.1 (sw/third_party/fonts/OFL.txt).",
       " * Converted format, so per the OFL this is a modified version and does not",
       " * carry the Reserved Font Name. ASCII 32..126, MSB = leftmost pixel. */",
       "#ifndef DZ_FONT_DATA_H", "#define DZ_FONT_DATA_H", "#include <stdint.h>", ""]
args = sys.argv[1:]
for name, path in zip(args[0::2], args[1::2]):
    w, h, glyphs, uni = load(path)
    bpr = (w + 7) // 8
    out.append("/* %s: %dx%d from %s */" % (name, w, h, path.split("/")[-1]))
    out.append("#define %s_W %d" % (name.upper(), w))
    out.append("#define %s_H %d" % (name.upper(), h))
    out.append("static const uint8_t %s[95][%d] = {" % (name, bpr * h))
    for c in range(32, 127):
        g = glyphs[uni[c]] if c in uni else bytes(bpr * h)
        out.append("\t{" + ",".join("0x%02x" % x for x in g[:bpr * h]) + "}, /* %r */" % chr(c))
    out.append("};\n")
out.append("#endif")
print("\n".join(out))
