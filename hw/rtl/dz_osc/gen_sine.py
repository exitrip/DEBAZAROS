#!/usr/bin/env python3
"""gen_sine.py - write dz_sine_rom.v: the quarter-wave sine table of the DDS
pattern engine (2026-10-29; ROADMAP.md section 14).

    python3 hw/rtl/dz_osc/gen_sine.py      (writes hw/rtl/dz_osc/dz_sine_rom.v)

1024 entries x 16 bit: q[i] = round(32767 * sin(2 pi (i + 0.5) / 4096)),
i = 0..1023 (the first quarter of a 4096-point sine; the half-step offset
makes the mirror for the second quarter exact). dz_osc_ch builds the full
wave from the top 12 phase bits: quadrant = phase[31:30], index =
phase[29:20], mirrored in quadrants 1 and 3, negated in 2 and 3. Spurs of
the 12-bit phase truncation are about -72 dBc - invisible in video.
A registered case ROM: Vivado maps it to one RAMB18, and the project needs
no .mem file (same approach as hw/rtl/hdmi_tx/gen_rom.py).
"""
import math
import os

N = 1024
q = [round(32767 * math.sin(2 * math.pi * (i + 0.5) / (4 * N))) for i in range(N)]

lines = [
    '// dz_sine_rom.v - GENERATED by gen_sine.py, do not edit: quarter-wave',
    '// sine, 1024 x 16 bit (q[i] = round(32767 sin(2 pi (i + 0.5) / 4096))),',
    '// registered output (one RAMB18).',
    '`timescale 1ns / 1ps',
    'module dz_sine_rom (',
    '    input  wire        clk,',
    '    input  wire [9:0]  addr,',
    '    output reg  [15:0] data = 0',
    ');',
    '    (* rom_style = "block" *) reg [15:0] rom;',
    '    always @* begin',
    '        case (addr)',
]
for i, v in enumerate(q):
    lines.append("            10'd%d: rom = 16'h%04X;" % (i, v & 0xFFFF))
lines += [
    "            default: rom = 16'h0000;",
    '        endcase',
    '    end',
    '    always @(posedge clk) data <= rom;',
    'endmodule',
    '',
]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'dz_sine_rom.v')
with open(out, 'w') as f:
    f.write('\n'.join(lines))
print('wrote %s (%d entries, max %d)' % (out, N, max(q)))
