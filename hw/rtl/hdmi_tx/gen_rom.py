#!/usr/bin/env python3
"""gen_rom.py - write hdmi_tx_rom.v: the constant data-island packets of
hdmi_tx, as the 9-bit per-pixel symbols that the packet assembler would make
(header bit + 2 x 4 subpacket bits, BCH ECC included), like the EDID ROM of
dvi2rgb. Run it after a change here, then simulate (hw/sim/run_hdmi_tx_tb.sh).

ROM address = {packet[2:0], pixel[4:0]}:
  0..3  AVI InfoFrame (RGB, IT content) with VIC 4 (720p60), 34 (1080p30),
        16 (1080p60), 0 (none)
  4     Audio InfoFrame (2 ch, coding/rate/size "refer to stream header")
  5..7  zero (Null packet)
"""
import os

AVI_VICS = [4, 34, 16, 0]


def ecc(bits):
    e = 0
    for b in bits:
        e = (e >> 1) ^ (0b10000011 if (e ^ b) & 1 else 0)
    return e


def bits_of(value, n):
    return [(value >> i) & 1 for i in range(n)]


def infoframe(header, pb):
    """header = [type, version, length]; pb[1..27]; returns (hdr24, [sub56]*4)"""
    pb = list(pb) + [0] * (28 - len(pb))
    pb[0] = (-(sum(header) + sum(pb[1:]))) & 0xFF
    hdr = header[0] | header[1] << 8 | header[2] << 16
    subs = [sum(pb[7 * k + b] << (8 * b) for b in range(7)) for k in range(4)]
    return hdr, subs


def symbols(hdr, subs):
    hb = bits_of(hdr, 24)
    hb += bits_of(ecc(hb), 8)
    sb = []
    for s in subs:
        b = bits_of(s, 56)
        sb.append(b + bits_of(ecc(b), 8))
    out = []
    for j in range(32):
        v = hb[j]
        for k in range(4):
            v |= sb[k][2 * j] << (1 + k)
            v |= sb[k][2 * j + 1] << (5 + k)
        out.append(v)
    return out


rom = []
for vic in AVI_VICS:
    # PB1 Y=0 (RGB); PB2 R=1000 (as picture); PB3 ITC=1; PB4 VIC
    rom += symbols(*infoframe([0x82, 0x02, 0x0D], [0, 0x00, 0x08, 0x80, vic]))
rom += symbols(*infoframe([0x84, 0x01, 0x0A], [0, 0x01]))     # CC = 2 channels
rom += [0] * (256 - len(rom))

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, 'hdmi_tx_rom.v'), 'w') as f:
    f.write('// hdmi_tx_rom.v - GENERATED by gen_rom.py: do not edit.\n'
            '// Constant data-island packets as 9-bit symbols per pixel (ECC included).\n'
            '// addr = {packet[2:0], pixel[4:0]}: 0-3 AVI (VIC %s), 4 Audio InfoFrame.\n'
            '`timescale 1ns / 1ps\n'
            'module hdmi_tx_rom (\n'
            '    input  wire [7:0] addr,\n'
            '    output reg  [8:0] data\n'
            ');\n'
            '    always @*\n'
            '        case (addr)\n' % ', '.join(map(str, AVI_VICS)))
    for a, v in enumerate(rom):
        if v:
            f.write("            8'd%d: data = 9'h%03x;\n" % (a, v))
    f.write("            default: data = 9'h000;\n"
            '        endcase\n'
            'endmodule\n')
print('hdmi_tx_rom.v: %d non-zero words' % sum(1 for v in rom if v))
